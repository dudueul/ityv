#!/usr/bin/env python3
# Generator of the independent known-answer vectors in vectors/ledger.txt.
#
# Run with:  python3 -I crates/ityv-ledger/vectors/generate.py
# It uses only the standard library (hashlib.sha3_512), implements the RFC 9162
# definitions of MTH, PATH and PROOF directly from the RFC text, applies the
# ityv prefixes (leaf 0x00, node 0x01, empty tree = SHA3-512("")), prints the
# vectors it generates and rewrites vectors/ledger.txt next to itself.
#
# This script is reference tooling for the verification ladder (V1 known
# answers, V5 second implementation), not part of the trusted computing base.
import hashlib
import os


def sha3(data: bytes) -> bytes:
    return hashlib.sha3_512(data).digest()


def leaf(x: bytes) -> bytes:
    return sha3(b"\x00" + x)


def node(left: bytes, right: bytes) -> bytes:
    return sha3(b"\x01" + left + right)


def split_point(n: int) -> int:
    """The largest power of two strictly smaller than n (n >= 2)."""
    k = 1
    while k * 2 < n:
        k *= 2
    return k


def mth(leaves: list[bytes]) -> bytes:
    n = len(leaves)
    if n == 0:
        return sha3(b"")
    if n == 1:
        return leaf(leaves[0])
    k = split_point(n)
    return node(mth(leaves[:k]), mth(leaves[k:]))


def path(m: int, leaves: list[bytes]) -> list[bytes]:
    n = len(leaves)
    if n == 1:
        return []
    k = split_point(n)
    if m < k:
        return path(m, leaves[:k]) + [mth(leaves[k:])]
    return path(m - k, leaves[k:]) + [mth(leaves[:k])]


def subproof(m: int, leaves: list[bytes], complete: bool) -> list[bytes]:
    n = len(leaves)
    if m == n:
        return [] if complete else [mth(leaves)]
    k = split_point(n)
    if m <= k:
        return subproof(m, leaves[:k], complete) + [mth(leaves[k:])]
    return subproof(m - k, leaves[k:], False) + [mth(leaves[:k])]


def proof(m: int, leaves: list[bytes]) -> list[bytes]:
    assert 0 < m < len(leaves)
    return subproof(m, leaves, True)


def main() -> None:
    leaves = [bytes([i]) * 64 for i in range(9)]
    out = [
        "# ityv-ledger known-answer vectors, generated by vectors/generate.py",
        "# (python3 -I, standard library only, RFC 9162 definitions with the ityv",
        "# prefixes). These are independent of the crate: the crate is checked",
        "# against them in tests/vectors.rs. Leaves L_i are 64 bytes of value i.",
        "# Regression vectors produced by the crate itself live in regression.txt.",
        "# Format: name = lowercase hex; paths are comma-separated hashes.",
        "empty_root = " + sha3(b"").hex(),
    ]
    for i in (0, 1):
        out.append(f"leaf_hash_L{i} = " + leaf(leaves[i]).hex())
    out.append("node_hash_L0_L1 = " + node(leaf(leaves[0]), leaf(leaves[1])).hex())
    for n in range(9):
        out.append(f"root_n{n} = " + mth(leaves[:n]).hex())
    for m, n in [(0, 1), (2, 5), (4, 5), (6, 7), (3, 8)]:
        out.append(
            f"inclusion_path_m{m}_n{n} = "
            + ",".join(h.hex() for h in path(m, leaves[:n]))
        )
    for a, b in [(1, 2), (2, 5), (3, 7), (4, 8), (5, 8), (7, 8)]:
        out.append(
            f"consistency_path_old{a}_new{b} = "
            + ",".join(h.hex() for h in proof(a, leaves[:b]))
        )
    sorted_set = sorted([leaves[3], leaves[1], leaves[2]])
    out.append("sorted_set_root_L1_L2_L3 = " + mth(sorted_set).hex())
    text = "\n".join(out) + "\n"
    print(text, end="")
    target = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ledger.txt")
    with open(target, "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    main()
